#include <stdio.h>

int main()
{
    printf("1、输出char、short、int、long、float、double 的大小（基础概念）\n");
    printf("char=%zu\n", sizeof(char));
    printf("int=%zu\n", sizeof(int));
    printf("short=%zu\n", sizeof(short));
    printf("long=%zu\n", sizeof(long));
    printf("float=%zu\n", sizeof(float));
    printf("double=%zu\n", sizeof(double));

    printf("----------------------------------------------------------------------------------------\n");
    
    printf("2、定义两个 char 类型的变量，一个赋值为 127，一个赋值为 128。再将其以%d 输出，看看输出了什么结果，并想想这是为什么？（基础概念）\n");
    char char1=127;
    char char2=128;
    printf("char1=%d\n", char1);
    printf("char2=%d\n", char2);//char2=-128,char类型范围是-128~127,128超出范围

    printf("----------------------------------------------------------------------------------------\n");

    printf("3、完成一个程序，用于计算阶乘（循环）\n");
    int a=0;
    int res1=1;
    printf ("请输入一个多位数:");
    scanf ("%d",&a );
    for (int i=1;i<=a;i++)
    {
        res1 =i*res1 ;
    }
    printf("%d!=%d\n",a,res1);

    printf("----------------------------------------------------------------------------------------\n");

    printf ("4、输入一个数，将这个数为数字为偶数的位去除后再输出（选择加循环）\n");
    int b=0;
    printf ("请输入一个多位数:");
    scanf ("%d",&b);
    int arr1[16];//int最大16位
    int num=0;
    while (b != 0)
    {
        int b1=b%10;//获取每一位上的数字
        b=b/10;//去除每一位上的数字

        if (b1 % 2 != 0)//判断是否为偶数
        {
            arr1[num]=b1;
            num++;
        }
    }
    for (int i=num-1 ;i>=0;i--)//倒着遍历
    {
        printf ("%d",arr1[i]);//直接一个个输出数字就好了
    }
    printf("\n");

    printf("----------------------------------------------------------------------------------------\n");

    printf("5、将一个数反向输出。（选择加循环）\n");
    int c=0;
    printf ("请输入一个多位数");
    scanf("%d",&c);
    int arr2[16];//存放从低位到高位取出的每一位
    int num2=0;//已经存了几位
    while(c!=0)
    {
        int c1=c%10;//取最低位
        c=c/10;//推进，丢掉已经取过的最低位
        arr2[num2]=c1;
        num2++;
    }
    for(int i=0;i<=num2-1;i++)//arr2里本来就从个位开始存的，正着遍历就是反向输出
    {
        if(arr2[i]==0)//去掉前导0：输入100反向是001，样例要求输出1，但我觉得没必要吧
        {
            continue;
        }
        else
        {
            printf("%d",arr2[i]);
        }
    }
    printf("\n");

    printf("----------------------------------------------------------------------------------------\n");

    printf("6、输入一个数，如果是偶数就除以 2，是奇数就乘 3 再加 1。得到的结果再进行同样的运算，直至得到 1 为止。输出一共运算的次数。(选择加循环)\n");
    int d=0;
    int times=0;//计数器
    printf ("请输入一个数：");
    scanf("%d",&d);
    while (d!=1)//一直算到 1 为止；输入 1 时循环一次都不进，times 保持 0
    {
        if (d%2==0)//偶数
        {
            d=d/2;
        }
        else//奇数
        {
            d=d*3+1;
        }
        times++;//每运算一次记一笔
    }
    printf("一共运算了%d次\n",times);

    printf("----------------------------------------------------------------------------------------\n");

    printf("7、输入一个二进制数，将其转化为十进制数和十六进制数再输出\n");
    int e=0;//存二进制的数
    int f=0;//当前取出的那一位
    int sum=0;//累加出来的十进制值
    int g=1;//位权，2的0次方，之后每轮乘2翻到下一个权位
    printf("请输入一个二进制数:");
    scanf("%d",&e);
    while(e!=0)//从最低位开始，一位一位往上处理
    {
        f=e%10;//取出最低位
        if(f!=1&&f!=0)//出现0、1以外的数字就不是二进制数
        {
            printf("不是二进制\n");
            goto end;//不对就不打印后面的了
        }
        e=e/10;//数字推进
        sum=sum+f*g;//当前位上的数乘上当前位权，加到总和上
        g=g*2;//一直乘2换成十进制
    }
    printf("%d  0x%X\n",sum,sum);
    end:

    return 0;
}